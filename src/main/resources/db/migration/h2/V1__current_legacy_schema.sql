-- Snapshot of the existing Hibernate-generated schema, not the planned V1 domain model.
CREATE TABLE app_user (
    id UUID NOT NULL PRIMARY KEY,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    school_class VARCHAR(40),
    username VARCHAR(80) NOT NULL,
    display_name VARCHAR(160) NOT NULL,
    external_subject VARCHAR(160) NOT NULL UNIQUE,
    role ENUM ('ADMIN', 'STUDENT', 'TEACHER') NOT NULL
);

CREATE TABLE games (
    id VARCHAR(255) NOT NULL PRIMARY KEY,
    created_at DATE,
    played_rounds INTEGER,
    created_by_id UUID,
    game_type VARCHAR(80) NOT NULL,
    subject VARCHAR(120),
    name VARCHAR(160) NOT NULL,
    teacher_name VARCHAR(160) NOT NULL,
    description VARCHAR(2000),
    CONSTRAINT fk_games_creator FOREIGN KEY (created_by_id) REFERENCES app_user(id)
);

CREATE TABLE game_branches (
    branch_order INTEGER NOT NULL,
    branch VARCHAR(200),
    game_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (branch_order, game_id),
    CONSTRAINT fk_game_branches_game FOREIGN KEY (game_id) REFERENCES games(id)
);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_order INTEGER,
    type VARCHAR(80) NOT NULL,
    text VARCHAR(2000) NOT NULL,
    game_id VARCHAR(255),
    CONSTRAINT fk_questions_game FOREIGN KEY (game_id) REFERENCES games(id)
);

CREATE TABLE answer_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_order INTEGER,
    is_correct BOOLEAN,
    question_id BIGINT,
    text VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_answer_options_question FOREIGN KEY (question_id) REFERENCES questions(id)
);
